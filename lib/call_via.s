	.include "macros.inc"

@ ============================================================================
@ The indirect-call veneers.
@
@ Fifteen two-instruction functions, one per register, linked at the front of
@ the ROM by stage1.ld. Each is just `bx <reg>`, and calling one is how Thumb
@ code performs an indirect call that can land on ARM code:
@
@     ldr  r3, =Func_1af8
@     bl   _call_via_r3          @ the `bl` sets lr, the `bx` switches mode
@
@ A bare `bx r3` would lose the return address, and Thumb has no `blx <reg>` on
@ ARMv4T -- so the compiler emits a call to one of these instead. Every
@ `_call_via_rN` in the sources is that pattern.
@
@ The `nop` after each `bx` is the macro keeping every entry four bytes, so the
@ set is uniform and each stays word-aligned.
@
@ Generated by the macro below, so a scan of the sources sees ONE
@ `.thumb_func_start` here rather than fifteen.
@ ============================================================================

	.macro call_via register
@ CallViaRegister -- `bx <reg>`, reached with `bl` so lr is set. See above.
.thumb_func_start _call_via_\register
	bx	\register
	nop
.func_end _call_via_\register
	.endm

