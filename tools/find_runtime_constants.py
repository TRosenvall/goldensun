#!/usr/bin/env python3
"""find_runtime_constants.py -- find constants the ROM computes at runtime.

The OvlFunc_974 family was found by accident and took two rounds to
understand. This is the search that would have found it in one, so the next
instance is cheap.

THE SIGNATURE

    ldr r3, =0xc9b
    ldr r1, =0xcc6
    sub r1, r3

Two literal pool loads feeding a register-register subtract, producing a value
that is constant. No compiler emits that from `0xcc6 - 0xc9b` -- it folds to a
single immediate and one pool word disappears. The ROM does it because the
operands were the ADDRESSES OF ABSOLUTE SYMBOLS in the original source, and
gcc cannot fold the difference between two link-time addresses.

THE FIX

Define the ids in message.sym (a linker fragment; the definitions emit no
bytes) and take their addresses:

    extern int _MSG_c9b;
    extern int _MSG_cc6;
    ...
    f(first, (int)&_MSG_cc6 - (int)&_MSG_c9b);

Which ids need to be symbols is NOT arbitrary. The operands of the
subtraction must be, or the fold comes back. Any other argument stays a plain
literal unless the ROM reuses the same register for it and for a side of the
subtraction, in which case it must be the symbol too. Getting that wrong costs
an instruction in either direction.

CAVEAT: message.sym is not a tracked dependency of stage1.o, so after adding
symbols there, delete stage1.o by hand or the overlays will not see them.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START = re.compile(r"\s*\.thumb_func_start\s+(\S+)", re.IGNORECASE)
POOL = re.compile(r"ldr\s+r\d+,\s*=(0x[0-9a-fA-F]+)$")
SUBR = re.compile(r"sub\s+r\d+,\s*r\d+(,\s*r\d+)?$")


def defined_symbols():
    """Ids already present in message.sym, so the report can say what is new."""
    out = set()
    p = os.path.join(ROOT, "message.sym")
    if os.path.exists(p):
        for line in open(p, errors="replace"):
            m = re.match(r"\s*\w+\s*=\s*(0[xX][0-9a-fA-F]+)\s*;", line)
            if m:
                out.add(int(m.group(1), 16))
    return out


def main():
    have = defined_symbols()
    rows, seen = [], set()

    for p in sorted(glob.glob(os.path.join(ROOT, "asm", "**", "*.s"), recursive=True)):
        L = open(p, errors="replace").read().split("\n")
        if not L or "Generated by gcc" in L[0]:
            continue
        cur = None
        body = 0
        for i, l in enumerate(L):
            m = START.match(l)
            if m:
                cur, body = m.group(1), 0
            elif re.match(r"^\s+[a-z]", l) and not l.strip().startswith("."):
                body += 1
            if not SUBR.match(l.strip()):
                continue
            lits = [POOL.match(x.strip()) for x in L[max(0, i - 5):i]]
            lits = [int(x.group(1), 16) for x in lits if x]
            if len(lits) < 2 or cur in seen:
                continue
            seen.add(cur)
            rows.append((cur, lits[-2], lits[-1], os.path.relpath(p, ROOT)))

    print(f"{'function':<26}{'operands':<22}{'symbols needed':<26}file")
    plausible = 0
    for fn, a, b, p in rows:
        # A message id is a small positive number. A pair like
        # 0xff880000/0xffa00000 is 16.16 fixed point, and 0x20/0x1000 is a
        # size or a mask -- the symbol idiom is about ids and does not apply
        # to those, so say so rather than suggesting a nonsense symbol name.
        if max(a, b) > 0xFFFF:
            note = "n/a -- not message ids"
        else:
            need = [v for v in (a, b) if v not in have]
            plausible += 1
            note = "none -- already defined" if not need else \
                   " ".join(f"_MSG_{v:x}" for v in need)
        print(f"{fn:<26}{'0x%x, 0x%x' % (a, b):<22}{note:<26}{p}")
    print(f"\n{len(rows)} functions computing a constant at runtime, "
          f"{plausible} of them plausibly message ids")
    print("See the module docstring for the idiom that reproduces it.")


if __name__ == "__main__":
    main()
