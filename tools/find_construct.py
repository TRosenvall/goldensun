#!/usr/bin/env python3
"""find_construct.py -- find the C behind a shape gcc "will not" emit.

THE METHOD, AND WHY IT IS A TOOL

The arg-interleave class stood for thirty-six batches. Every attempt on it
generated variants of the C and screened them, and the park note eventually
concluded "the C is not the variable". What actually cracked it was the
opposite direction: SEARCH GCC'S OWN OUTPUT for places it already emits the
shape, then read those sources.

That works because the build writes gcc's assembly to asm/<path>.s beside the
hand-written corpus, so ~2,400 solved functions are sitting in the tree in the
same representation as the unsolved ones. It is a labelled dataset: every
generated .s is an answer whose question is the .c next to it.

Doing it by hand took a morning and one wrong turn. This is the same procedure,
repeatable:

    1. --shape RE      lines whose text matches, in generated output
    2. --window N      report the N instructions around each hit
    3. fakematches are flagged, because a shape reached with inline asm
       tells you nothing about what the compiler does unaided

WHAT IT IS NOT. It finds correlations, not rules. Every hand-written probe in
reports/arg-interleave.md was needed to turn "these six files have it" into
"the assignment must cross a basic-block boundary" -- and two of the five probes
came out contiguous, which is what ruled out the simpler explanations. Read the
sources, form a hypothesis, then vary ONE thing at a time.

EXAMPLES

    # where does gcc rematerialise the same small constant twice?
    python3 tools/find_construct.py --dup-imm

    # where does gcc emit `mov rA / mov rB / lsl rA` (arg-interleave)?
    python3 tools/find_construct.py --shape '^\\tmov\\t(r[0-3]), #\\d+$' --triple

    # any regex, with context
    python3 tools/find_construct.py --shape 'neg\\tr' --window 3
"""
import collections
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN_FUNC = re.compile(r"\.thumb_func\s*\n\s*\.type\s+(\S+),function\s*\n\1:\n"
                      r"(.*?)(?=\n\s*\.size|\n\s*\.align|\Z)", re.S)
MOVI = re.compile(r"^\tmov\t(r\d+), #(\d+)$")
NEG = re.compile(r"^\tneg\t(r\d+), (r\d+)$")


def generated():
    """(source path, function name, instruction lines) for every solved function."""
    for p in sorted(glob.glob(os.path.join(ROOT, "asm/**/*.s"), recursive=True)):
        txt = open(p, errors="replace").read()
        if not txt.startswith("@ Generated by gcc"):
            continue
        src = os.path.join("src", os.path.relpath(p, ROOT)[len("asm/"):])[:-2] + ".c"
        if not os.path.exists(os.path.join(ROOT, src)):
            continue
        fake = "fakematch" in open(os.path.join(ROOT, src), errors="replace").read()
        for m in GEN_FUNC.finditer(txt):
            lines = [l for l in m.group(2).split("\n")
                     if l.startswith("\t") and not l.lstrip().startswith(".")]
            yield src, fake, m.group(1), lines


def dup_imm():
    """Functions where gcc materialises the SAME immediate more than once.

    This is the query for the class that three parked shapes share: the ROM
    rebuilds a constant and gcc holds it in a register. Anywhere gcc rebuilds
    one twice by itself is a place to read.
    """
    out = []
    for src, fake, name, lines in generated():
        c = collections.Counter()
        for l in lines:
            m = MOVI.match(l)
            if m:
                c[m.group(2)] += 1
        dup = [k for k, v in c.items() if v > 1]
        if dup:
            out.append((src, fake, name, dup, len(lines)))
    return out


def shape(rx, window, triple):
    out = []
    cre = re.compile(rx)
    for src, fake, name, lines in generated():
        for i, l in enumerate(lines):
            if not cre.match(l):
                continue
            if triple:
                # mov rA / mov rB / lsl rA
                a = MOVI.match(lines[i])
                b = MOVI.match(lines[i + 1]) if i + 1 < len(lines) else None
                c = (re.match(r"^\tlsl\t(r[0-3]), r[0-3], #", lines[i + 2])
                     if i + 2 < len(lines) else None)
                if not (a and b and c and c.group(1) == a.group(1)
                        and b.group(1) != a.group(1)):
                    continue
            out.append((src, fake, name,
                        lines[max(0, i - window):i + window + 1]))
    return out


def main():
    a = sys.argv[1:]
    window = int(a[a.index("--window") + 1]) if "--window" in a else 2
    lim = int(a[a.index("--limit") + 1]) if "--limit" in a else 30
    if "--dup-imm" in a:
        rows = dup_imm()
        real = [r for r in rows if not r[1]]
        print(f"{len(rows)} solved functions materialise an immediate twice; "
              f"{len(real)} are not fakematches\n")
        for src, fake, name, dup, n in sorted(real, key=lambda r: r[4])[:lim]:
            print(f"  {n:4d} insn  {name:28s} dup {','.join(dup):16s} {src}")
        return 0
    if "--shape" in a:
        rows = shape(a[a.index("--shape") + 1], window, "--triple" in a)
        real = [r for r in rows if not r[1]]
        print(f"{len(rows)} sites, {len(real)} outside fakematches\n")
        for src, fake, name, blk in real[:lim]:
            print(f"--- {name}  {src}")
            for l in blk:
                print("      " + l.strip())
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
