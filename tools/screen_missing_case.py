#!/usr/bin/env python3
"""screen_hidden_case.py -- find ROM switches that MUST carry a case value
outside their visible range.

THE RULE, measured in batch 308 (see PARK_BufferString.c lever 1):

  stmt.c's expand_end_case takes the DECISION TREE instead of a jump table when

      count < case_values_threshold()        (= 5 in this build, probed)
   || (unsigned) range > 10 * count          (range = maxval - minval)

  So a ROM dispatch that IS a gcc decision tree, over >= 5 distinct case
  values whose span is <= 10 * count, CANNOT have come from a switch holding
  only those values -- the same source would have produced a jump table.  The
  source carries at least one more case whose value is far outside the visible
  span.  For an UNSIGNED selector `case -1:` (0xFFFFFFFF) is always sufficient
  and is what BufferString turned out to have, twice.

THE SIGNATURE of emit_case_nodes, and what tells it from a hand-written
if-chain: the tree tests one node with `beq` and then RE-COMPARES THE SAME
REGISTER AGAINST THE SAME CONSTANT for the range branch, so

    cmp rN, #K / b<eq> .. / cmp rN, #K / b<hi|cc|gt|lt> ..

appears at every interior node.  No hand-written chain repeats a compare.
"""
import os, re, sys

CMP = re.compile(r"^\s*cmp\s+(r\d+|sl|fp|ip),\s*#(0x[0-9a-fA-F]+|\d+)\s*$")
BR = re.compile(r"^\s*b(eq|ne|hi|ls|cc|cs|lo|hs|gt|lt|ge|le)\s")
FSTART = re.compile(r"^\.(thumb|arm)_func_start\s+(\S+)")
FEND = re.compile(r"^\.func_end(?:_emit_size)?\s+(\S+)")
# gcc's own .s has no .thumb_func_start: it labels at column 0 and closes with
# `.size NAME,.LfeN-NAME`.  Missing this is what made the first run of this
# screen report ZERO compiler-generated sites, which was a DETECTOR BUG and not
# a validation -- recorded so nobody reads that number as evidence again.
GSTART = re.compile(r"^([A-Za-z_][A-Za-z_0-9]*):\s*$")
GEND = re.compile(r"^\s*\.size\s")
THRESHOLD = 5

def scan(path):
    gen = False
    out = []
    try:
        lines = open(path, encoding="utf-8", errors="replace").read().splitlines()
    except OSError:
        return gen, out
    if lines and "Generated by gcc" in "\n".join(lines[:4]):
        gen = True
    name = None
    body = []
    for ln in lines:
        m = FSTART.match(ln) or (GSTART.match(ln) if gen else None)
        if m:
            if name:
                out.extend(analyse(name, body))
            name, body = m.group(m.lastindex), []
            continue
        if (FEND.match(ln) or (GEND.match(ln) if gen else None)) and name:
            out.extend(analyse(name, body))
            name = None
            continue
        if name is not None:
            body.append(ln)
    if name:
        out.extend(analyse(name, body))
    return gen, out

def analyse(name, body):
    # group cmp/branch pairs by register into clusters separated by >12 other insns
    events = []          # (index, reg, value)
    for i, ln in enumerate(body):
        m = CMP.match(ln)
        if m:
            events.append((i, m.group(1), int(m.group(2), 0)))
    res = []
    byreg = {}
    for i, reg, val in events:
        byreg.setdefault(reg, []).append((i, val))
    for reg, evs in byreg.items():
        cluster = []
        for i, val in evs:
            if cluster and i - cluster[-1][0] > 6:
                res += emit(name, reg, cluster, body)
                cluster = []
            cluster.append((i, val))
        res += emit(name, reg, cluster, body)
    return res

def emit(name, reg, cluster, body):
    if len(cluster) < 6:
        return []
    # emit_case_nodes signature: same constant compared twice within 4 insns
    dbl = 0
    for a in range(len(cluster) - 1):
        i, v = cluster[a]
        j, w = cluster[a + 1]
        if v == w and j - i <= 4:
            dbl += 1
    if dbl < 2:
        return []
    vals = sorted(set(v for _, v in cluster))
    # 0xff/0x1f style guard compares live in the same window; the node set is
    # what the doubled compares name, plus every value tested with beq.
    count = len(vals)
    span = vals[-1] - vals[0]
    if count >= THRESHOLD and span <= 10 * count:
        return [(name, reg, count, span, vals, dbl)]
    return []

def main():
    hand, gener = [], []
    for root, _, files in os.walk("asm"):
        for f in files:
            if not f.endswith(".s"):
                continue
            p = os.path.join(root, f)
            gen, hits = scan(p)
            for h in hits:
                (gener if gen else hand).append((p,) + h)
    for label, rows in (("HAND-WRITTEN (candidates)", hand),
                        ("COMPILER-GENERATED (controls)", gener)):
        print("=== %s: %d switch site(s)" % (label, len(rows)))
        for p, nm, reg, count, span, vals, dbl in sorted(rows):
            print("  %-56s %-22s %s count=%d span=%d dbl=%d vals=%s"
                  % (p, nm, reg, count, span, dbl,
                     ",".join(hex(v) for v in vals[:14])))

main()
