#!/usr/bin/env python3
"""sym_candidates.py -- pool-tell functions whose symbols already exist, by NAMESPACE.

WHY

The pool tell says an operand was a symbol: the ROM spends a literal-pool word on
a value that `mov #imm8` or `cmp #imm8` could build, and gcc-2.96 only does that
for a symbol's address. Such a function cannot match until the C names the
symbol -- see area.sym's header for the full argument.

What batch 65 established is that MOST OF THEM ARE NOT WAITING ON A NAME. The
four .sym files already define 611 symbols, and 209 of the 270 pool-tell
functions use values that are all already defined. They were blocked on nobody
looking.

WHY VALUE LOOKUP ALONE IS WRONG

95 small values are defined in MORE THAN ONE namespace -- 0x68 is both
`_AREA_68` and `_FILE_68`. Both emit the same word, so a value-only lookup
produces a byte-correct ROM that asserts a false thing about the code. That is
exactly what docs/names.md's `Basis` column exists to prevent.

THE CONSUMER DECIDES, and the rule was read off existing elevated code:

    _FILE_xx   the value is passed to GetFile()
    _MSG_xx    the value is passed to the message calls (Func_801776c, Func_8017658)
    _AREA_xx   the value is COMPARED AGAINST the halfword at gState+0x1C0

    python3 tools/sym_candidates.py [area|file|msg]

Only `area` is classified confidently today: reading gState+0x1C0 is a distinct
instruction signature (`mov rN, #0xe0 / lsl rN, #1`) that cannot be confused
with anything else. `file` and `msg` are reported as UNCLASSIFIED with their
call targets listed, so the consumer can be identified by hand before a name is
chosen. Do not guess from the value.
"""
import glob
import re
import sys

AREA_FIELD = re.compile(r"mov\tr\d+, #0xe0\n\tlsl\tr\d+, #1")
HAND = re.compile(r"\.thumb_func_start\s+(\S+)[^\n]*\n(.*?)\.func_end", re.S)
POOL = re.compile(r"^\tldr\t(r\d+), =(0x[0-9a-f]+|\d+)\s*$", re.M)
CALL = re.compile(r"^\tbl\t(\S+)", re.M)


def symbols():
    ns = {}
    for f in sorted(glob.glob("*.sym")):
        for m in re.finditer(r"^(\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*;", open(f).read(), re.M):
            ns.setdefault(int(m.group(2), 0), []).append(m.group(1))
    return ns


def parked_names():
    out = set()
    for c in glob.glob("src/non_matching/**/*.c", recursive=True):
        m = re.match(r"/\*\s*(\w+)\s", open(c, errors="replace").read())
        if m:
            out.add(m.group(1))
    return out


def main():
    want = sys.argv[1] if len(sys.argv) > 1 else "area"
    ns, parked = symbols(), parked_names()
    areas = {v for v, names in ns.items() if any(n.startswith("_AREA_") for n in names)}
    rows, unclassified = [], []
    for p in sorted(glob.glob("asm/**/*.s", recursive=True)):
        if p.startswith("asm/rom_f9000/"):
            continue
        t = open(p, errors="replace").read()
        if "Generated by gcc" in t[:400]:
            continue
        for m in HAND.finditer(t):
            n, b = m.group(1), m.group(2)
            vals = [int(v, 0) for _, v in POOL.findall(b) if int(v, 0) < 0x100]
            if not vals:
                continue
            ins = len([l for l in b.split("\n") if l.startswith("\t")])
            if AREA_FIELD.search(b) and all(v in areas for v in vals):
                rows.append((ins, n, p, sorted({f"_AREA_{v:02x}" for v in vals}), n in parked))
            else:
                unclassified.append((ins, n, p, sorted({hex(v) for v in vals}),
                                     sorted(set(CALL.findall(b)))[:3]))
    rows.sort()
    unclassified.sort()
    if want == "area":
        print(f"{len(rows)} functions read gState+0x1C0 and compare only DEFINED area ids\n")
        for ins, n, p, syms, pk in rows:
            print("%3d insn  %-24s %-30s %s%s"
                  % (ins, n, ",".join(syms), p, "  [parked]" if pk else ""))
    else:
        print(f"{len(unclassified)} pool-tell functions NOT classified as area.")
        print("Identify the consumer before naming -- call targets shown.\n")
        for ins, n, p, vals, calls in unclassified[:40]:
            print("%3d insn  %-24s %-18s %s" % (ins, n, ",".join(vals), ",".join(calls)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
