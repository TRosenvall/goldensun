#!/bin/sh
# guard_generated.sh -- refuse to commit a compiler-generated .s
#
# WHY THIS EXISTS
#
# Converting a .s to C leaves the build free to regenerate a .s at the SAME
# PATH from the new .c. `git add <that path>` then stages a MODIFICATION of the
# hand-written file instead of its deletion, and the commit records
# compiler output as though it were source. CLAUDE.md forbids exactly that.
#
# It is not a rare slip. It happened on a single-function conversion in batch
# 221 and needed an amend, and the same shape recurred three times in batch 223
# -- every time the .s held exactly one function and was converted whole.
#
# It used to be an ad-hoc shell loop retyped per commit, and once it was
# CHAINED to the `git commit` in one command, so it printed its warning and the
# commit went through anyway. That is the failure this file removes: a check
# you retype is a check you can forget to read.
#
#   tools/guard_generated.sh          -- report and exit 1 if any are staged
#   tools/guard_generated.sh --fix    -- unstage them (git rm --cached), then
#                                        re-check and exit 0 if clean
#
# RUN IT AS ITS OWN STEP, never joined to the commit with && or ;.
set -e
cd "$(git rev-parse --show-toplevel)"

staged_generated() {
    git diff --cached --name-status --diff-filter=AM |
    awk '/\.s$/ {print $NF}' |
    while read -r f; do
        [ -f "$f" ] || continue
        if head -1 "$f" | grep -q "Generated by gcc"; then printf '%s\n' "$f"; fi
    done
}

bad=$(staged_generated)

if [ -n "$bad" ] && [ "$1" = "--fix" ]; then
    printf '%s\n' "$bad" | while read -r f; do
        [ -n "$f" ] || continue
        echo "unstaging generated: $f"
        git rm -q --cached "$f"
    done
    bad=$(staged_generated)
fi

if [ -n "$bad" ]; then
    echo "REFUSING: compiler-generated .s staged:"
    printf '  %s\n' $bad
    echo "re-run with --fix to unstage, then commit"
    exit 1
fi

echo "guard clean: no generated .s staged"
