#!/usr/bin/env python3
"""port_overlay_annotations.py -- move our overlay prose onto this tree.

Overlays need their own porter because they are addressed differently from the
main ROM:

  ours    overlays/rom_780898/ovl_30.s, `.thumb_func_start OvlFunc_30`
          -- the offset within the overlay
  theirs  asm/overlays/rom_780898/..., `.thumb_func_start OvlFunc_883_2008030`
          -- overlay index plus the VRAM address it loads at

Overlays link at 0x02008000, so our offset 0x30 is their 0x02008030. The
overlay directory name disambiguates, so the index in their symbol is not
needed.

TWO HAZARDS, both of which will silently waste the work if ignored:

  1. asm/overlays/ holds BOTH hand-written assembly and .s files GENERATED
     from .c by the build. Annotating a generated file is pointless -- the
     next build overwrites it. They are identified by their first line,
     `@ Generated by gcc`.
  2. `common` uses a different scheme (OvlFunc_common0_0), where the trailing
     number is an index rather than an address. Handled separately.
"""
import json, re, sys, os, glob
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OVL_BASE = 0x02008000


def is_generated(path):
    with open(path, errors="replace") as f:
        return "Generated by gcc" in (f.readline() or "")


def their_overlay_functions():
    """(overlay_dir, offset) -> (symbol, path, line index)."""
    out = {}
    for p in glob.glob(os.path.join(ROOT, "asm", "overlays", "*", "*.s")):
        if is_generated(p):
            continue
        ovl = os.path.basename(os.path.dirname(p))
        L = open(p, errors="replace").read().split("\n")
        for i, l in enumerate(L):
            m = re.match(r"\s*\.thumb_func_start\s+OvlFunc_\d+_([0-9a-fA-F]+)\s*$", l)
            if m:
                out[(ovl, int(m.group(1), 16) - OVL_BASE)] = (l.split()[1], p, i)
    return out


def main():
    apply = "--apply" in sys.argv

    ann = json.load(open(os.path.join(ROOT, "ANNOTATIONS.json")))
    ours = {}
    for items in ann.values():
        for it in items:
            if it["overlay"] and it["addr"] is not None:
                ours[(it["overlay"], it["addr"])] = it["text"]

    theirs = their_overlay_functions()
    gen = sum(1 for p in glob.glob(os.path.join(ROOT, "asm", "overlays", "*", "*.s"))
              if is_generated(p))
    print(f"our overlay annotations: {len(ours)}")
    print(f"their hand-written overlay functions: {len(theirs)}"
          f"  ({gen} generated .s files skipped)")

    per_file = defaultdict(list)
    for key, text in ours.items():
        if key in theirs:
            sym, path, idx = theirs[key]
            per_file[path].append((idx, text))

    placed = skipped = 0
    for path in sorted(per_file):
        L = open(path, errors="replace").read().split("\n")
        ins = {}
        for idx, text in per_file[path]:
            j = idx - 1
            while j >= 0 and not L[j].strip():
                j -= 1
            if j >= 0 and L[j].lstrip().startswith("@"):
                skipped += 1
                continue
            ins[idx] = ["@ " + x if x else "@" for x in text.split("\n")]
            placed += 1
        if ins and apply:
            out = []
            for i, line in enumerate(L):
                if i in ins:
                    out.extend(ins[i])
                out.append(line)
            open(path, "w").write("\n".join(out))

    print(f"\nannotations placed: {placed}")
    print(f"already annotated (left alone): {skipped}")
    print(f"unmatched (no counterpart in their asm/): {len(ours) - placed - skipped}")
    print(f"files touched: {len(per_file) if apply else 0}")
    if not apply:
        print("\n(dry run -- pass --apply to write)")


if __name__ == "__main__":
    main()
