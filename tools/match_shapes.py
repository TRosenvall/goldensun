#!/usr/bin/env python3
"""match_shapes.py -- find ROM functions shaped like one we have ALREADY matched.

WHY THIS EXISTS

Batch 32 was nine functions, and five of them came from noticing by hand that a
shape which had just matched probably had siblings, then grepping asm/ for them.
Four of those five matched on the FIRST screen. Nothing in the tooling looks for
that, and it is the strongest signal available:

  tools/elevation_candidates.py   ranks by tractability -- size, calls, branches
  tools/pick_candidates.py        ranks by "unlikely to hit a known blocker"
  tools/find_twins.py             groups REMAINING asm by exact body
  this                            matches remaining asm against the SOLVED corpus

The first three answer "what looks easy". This one answers "what looks like
something we can already write", which is a different and better question,
because a shape that matched once comes with a finished .c to copy.

HOW IT WORKS

Every elevated function leaves its gcc output in asm/<path>.s -- the build writes
the generated assembly beside the hand-written corpus and overwrites the original
(see the `asm/%.o: src/%.c` rule in the Makefile). Those files are identifiable:
they start with `@ Generated by gcc`. So the solved corpus is already sitting in
the tree in assembly form, and can be compared against the unsolved corpus
directly, in the one representation both have.

Bodies are reduced to a SKELETON: mnemonic plus operand KINDS, with registers,
immediates, memory operands and symbols each collapsed to one letter. Two
functions with the same skeleton differ only in constants, registers and callee
names -- which is exactly the relationship between a function and its twin in
another overlay, and exactly what makes "copy the .c and change the numbers"
work.

WHAT THE STRICTNESS BUYS

Immediates are collapsed, so `mov r0, #2` and `mov r0, #3` are the same shape.
Callee names are collapsed too, which is the loosest part of this and the reason
the report prints the exemplar's path: a shape match is a lead, not a proof, and
the .c has to be read before it is copied. tools/find_families.py's docstring
records what a genuinely loose match cost -- nine false positives and two
reverted splits -- so this stops well short of that: the instruction COUNT, the
mnemonic SEQUENCE and every operand's kind all have to agree exactly.

Functions already parked are skipped, as in pick_candidates.py.

    python3 tools/match_shapes.py                # every lead, best shapes first
    python3 tools/match_shapes.py --min-insn 12  # skip the trivial wrappers
    python3 tools/match_shapes.py --show <name>  # one lead's exemplars
    python3 tools/match_shapes.py --near 1       # one line off a solved shape
"""
import collections
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ROM_FUNC = re.compile(r"\.thumb_func_start\s+(\S+)[^\n]*\n(.*?)\.func_end", re.S)
GEN_FUNC = re.compile(r"\.thumb_func\s*\n\s*\.type\s+(\S+),function\s*\n"
                      r"\1:\n(.*?)(?=\n\s*\.size|\n\s*\.align|\Z)", re.S)
REG = re.compile(r"^(r\d+|sp|lr|pc)$")


def kind(op):
    op = op.strip()
    if REG.match(op):
        return "R"
    if op.startswith("#"):
        return "I"
    if op.startswith("[") or op.endswith("]"):
        return "M"
    if op.startswith("{"):
        return "K"
    return "S"


def skeleton(body):
    """Mnemonic sequence with every operand reduced to its kind."""
    out = []
    for line in body.split("\n"):
        if not line.startswith("\t") or line.lstrip().startswith(("@", ".")):
            continue
        parts = line.strip().split(None, 1)
        if not parts:
            continue
        mn = parts[0]
        if mn in ("bl", "b", "beq", "bne", "bge", "ble", "bgt", "blt",
                  "bcs", "bcc", "bhi", "bls", "bx"):
            # branch targets are names or labels; the DESTINATION is what
            # varies between siblings, the branch itself is the shape
            out.append(mn)
            continue
        if len(parts) == 1:
            out.append(mn)
            continue
        ops = [o.strip() for o in re.split(r",(?![^\[]*\])", parts[1])]
        # THE DESTRUCTIVE-FORM COLLAPSE, and it is load-bearing. gcc emits
        # `lsl r2, r2, #2`; the ROM's disassembly writes the same instruction
        # `lsl r2, #2`. Without folding those together the two corpora share
        # almost no shapes at all -- this tool reported 4 leads before the
        # fold and 20 after, from the same tree. tools/tryc.py has
        # normalised this since its first version; it had to be rediscovered
        # here because a skeleton looks nothing like an instruction diff.
        if len(ops) == 3 and REG.match(ops[0]) and ops[0] == ops[1]:
            ops = [ops[0], ops[2]]
        out.append(mn + " " + ",".join(kind(o) for o in ops))
    return "\n".join(out)


def parked_names():
    out = set()
    for p in glob.glob(os.path.join(ROOT, "src/non_matching/**/*.c"),
                       recursive=True):
        txt = open(p, errors="replace").read()
        out.update(re.findall(r"\b((?:Ovl)?Func_\w+)\s*\(", txt))
        m = re.match(r"/\*\s*(\S+)", txt)
        if m:
            out.add(m.group(1))
    return out


def scan():
    """(solved, unsolved) skeleton maps."""
    solved = collections.defaultdict(list)
    unsolved = collections.defaultdict(list)
    skip = parked_names()
    for p in sorted(glob.glob(os.path.join(ROOT, "asm/**/*.s"), recursive=True)):
        rel = os.path.relpath(p, ROOT)
        txt = open(p, errors="replace").read()
        if txt.startswith("@ Generated by gcc"):
            src = os.path.join("src", rel[len("asm/"):])[:-2] + ".c"
            if not os.path.exists(os.path.join(ROOT, src)):
                continue
            for m in GEN_FUNC.finditer(txt):
                body = m.group(2)
                n = len([l for l in body.split("\n") if l.startswith("\t")])
                solved[skeleton(body)].append((m.group(1), src, n))
        else:
            for m in ROM_FUNC.finditer(txt):
                if m.group(1) in skip:
                    continue
                body = m.group(2)
                n = len([l for l in body.split("\n") if l.startswith("\t")])
                unsolved[skeleton(body)].append((m.group(1), rel, n))
    return solved, unsolved


def near_matches(solved, unsolved, tol):
    """Pair each unsolved skeleton with a solved one differing in <= tol lines.

    WHY LOOSEN AT ALL. The exact mode drains: once every shape with a matched
    exemplar has been elevated, it reports nothing until more work is done. But
    a function that differs from a solved one in ONE line is still most of a
    finished .c -- the structure, the levers and the declarations all carry, and
    only the differing instruction has to be reasoned about.

    WHY THIS IS STILL NARROW. Only skeletons of the SAME LENGTH are compared,
    and the differing lines are printed, so the cost of a bad lead is reading
    two lines rather than a round. tools/find_families.py's docstring records
    what an unbounded loose match cost -- nine false positives and two reverted
    splits -- and the difference is that this compares whole normalised bodies
    positionally rather than looking for shared substrings.
    """
    by_len = collections.defaultdict(list)
    for key in solved:
        by_len[key.count("\n")].append(key)
    out = []
    for key, rows in unsolved.items():
        if key in solved:
            continue
        lines = key.split("\n")
        best = None
        for cand in by_len.get(len(lines) - 1, ()):
            cl = cand.split("\n")
            d = [(i, a, b) for i, (a, b) in enumerate(zip(lines, cl)) if a != b]
            if len(d) <= tol and (best is None or len(d) < len(best[1])):
                best = (cand, d)
        if best:
            out.append((rows, solved[best[0]], best[1]))
    return out


def main():
    a = sys.argv[1:]
    min_insn = int(a[a.index("--min-insn") + 1]) if "--min-insn" in a else 8
    solved, unsolved = scan()

    if "--near" in a:
        tol = int(a[a.index("--near") + 1])
        rowsets = near_matches(solved, unsolved, tol)
        rowsets = [(r, e, d) for r, e, d in rowsets
                   if any(x[2] >= min_insn for x in r)]
        rowsets.sort(key=lambda t: (len(t[2]), -t[0][0][2]))
        print(f"{'diff':>4} {'insn':>5}  lead / exemplar / what differs")
        for rows, ex, d in rowsets[:int(a[a.index("--limit") + 1])
                                   if "--limit" in a else 20]:
            n, rel, i = rows[0]
            en, esrc, _ = ex[0]
            print(f"{len(d):4d} {i:5d}  {n}  {rel}")
            print(f"{'':11s}  <- {en}  {esrc}")
            for pos, x, y in d[:3]:
                print(f"{'':11s}     @{pos}  rom {x!r}  exemplar {y!r}")
        print(f"\n{len(rowsets)} near shapes within {tol} line(s)")
        return 0

    leads = []
    for key, rows in unsolved.items():
        if key not in solved:
            continue
        rows = [r for r in rows if r[2] >= min_insn]
        if rows:
            leads.append((rows, solved[key]))
    leads.sort(key=lambda t: (-len(t[0]), -t[0][0][2]))

    if "--show" in a:
        want = a[a.index("--show") + 1]
        for rows, ex in leads:
            if any(n == want for n, _, _ in rows):
                print("exemplars already matched:")
                for n, src, i in ex:
                    print(f"    {n:26s} {i:4d} insn  {src}")
                print("leads:")
                for n, rel, i in rows:
                    print(f"    {n:26s} {i:4d} insn  {rel}")
                return 0
        print(f"no lead named {want}")
        return 1

    print(f"{'leads':>5} {'insn':>5}  first lead / exemplar to copy")
    for rows, ex in leads:
        n, rel, i = rows[0]
        en, esrc, _ = ex[0]
        print(f"{len(rows):5d} {i:5d}  {n}  {rel}")
        print(f"{'':11s}  <- {en}  {esrc}")
    print(f"\n{len(leads)} shapes, {sum(len(r) for r, _ in leads)} functions "
          f"with an already-matched exemplar")
    return 0


if __name__ == "__main__":
    sys.exit(main())
