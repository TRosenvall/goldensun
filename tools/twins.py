#!/usr/bin/env python3
"""twins.py -- find UNSOLVED functions whose instruction shape already matches a SOLVED one.

    python3 tools/twins.py [--top=N] [--exact]

WHY. `OvlFunc_956_2009a0c` and `OvlFunc_955_20090dc` are the same 207-instruction
cutscene differing in ONE immediate (a message id, 0x20e9 against 0x20ed).
Once the first was solved, the second fell byte-exact on the FIRST screen by
copying the candidate and changing that constant -- no pin re-derived, no fill
re-ordered, no statement moved. That is the cheapest match this project has had.

Nothing looks for that. neighbour.py and templated.py both rank on SHARED
SYMBOLS, which answers "is there a worked example nearby" -- a good question,
and a different one. Two functions can share every callee and still have
completely different bodies. This asks the strict question instead: is there a
solved function with the IDENTICAL OPCODE SEQUENCE?

THE SIGNATURE IS MNEMONICS ONLY, OPERANDS DISCARDED. That is deliberate. A twin
differs precisely in its operands -- the message id, the actor slot, the
coordinates -- so any signature including them would fail to group the very
pairs this is for. Registers are excluded for the same reason: allocation can
differ where shape does not.

FALSE POSITIVES ARE EXPECTED AND CHEAP. Short functions collide trivially
(a dozen `mov`/`bl` pairs is not a twin), so anything under MIN_INSNS is
dropped and the report is ordered longest-first: a 207-instruction signature
collision is near-certainly a real twin, a 20-instruction one is noise.

The solved corpus is read from GENERATED .s (`@ Generated by gcc`), which is
what a matching .c emits and therefore byte-equivalent to the ROM's own code.
The hand-written .s that a solved function came from is deleted at landing, so
the generated file is the only copy left -- and the right one to compare to.
"""
import os
import re
import sys
import glob
import collections

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from filtered import hand_written, arm_functions

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START = re.compile(r"^\s*\.(?:thumb|arm)_func_start(?:_noalign)?\s+(\S+)")
END = re.compile(r"^\s*\.func_end\b")
GEN_TYPE = re.compile(r"^\s*\.type\s+(\S+)\s*,\s*function")
GEN_SIZE = re.compile(r"^\s*\.size\s+(\S+)\s*,")
MIN_INSNS = 40


def mnemonics(body):
    """Opcode sequence, operands discarded -- a twin differs only in operands."""
    out = []
    for l in body:
        t = l.strip()
        if not t or t.startswith(("@", "/*", "*", ".")):
            continue
        if t.endswith(":"):
            continue
        out.append(t.split()[0].lower())
    return tuple(out)


def funcs_handwritten(lines):
    starts = [(i, m.group(1)) for i, l in enumerate(lines) if (m := START.match(l))]
    for k, (i, name) in enumerate(starts):
        stop = starts[k + 1][0] if k + 1 < len(starts) else len(lines)
        for j in range(i + 1, stop):
            if END.match(lines[j]):
                stop = j
                break
        yield name, lines[i + 1:stop]


def funcs_generated(lines):
    names = [(i, m.group(1)) for i, l in enumerate(lines) if (m := GEN_TYPE.match(l))]
    for i, name in names:
        start = None
        for j in range(i, min(i + 4, len(lines))):
            if lines[j].strip() == name + ":":
                start = j + 1
                break
        if start is None:
            continue
        stop = len(lines)
        for j in range(start, len(lines)):
            m = GEN_SIZE.match(lines[j])
            if m and m.group(1) == name:
                stop = j
                break
        yield name, lines[start:stop]


def main():
    top, exact_only = 40, False
    for a in sys.argv[1:]:
        if a.startswith("--top="):
            top = int(a.split("=", 1)[1])
        elif a == "--exact":
            exact_only = True

    solved = collections.defaultdict(list)   # signature -> [(name, path)]
    unsolved = []                            # (name, path, signature, body)
    for s in glob.glob(os.path.join(ROOT, "asm/**/*.s"), recursive=True):
        lines = open(s, errors="ignore").readlines()
        gen = any(".gcc2_compiled." in l or "Generated by gcc" in l for l in lines[:40])
        rel = os.path.relpath(s, ROOT)
        if gen:
            for name, body in funcs_generated(lines):
                sig = mnemonics(body)
                if len(sig) >= MIN_INSNS:
                    solved[sig].append((name, rel))
        else:
            if hand_written(s):
                continue
            arm = arm_functions(s)
            for name, body in funcs_handwritten(lines):
                if name in arm:
                    continue
                sig = mnemonics(body)
                if len(sig) >= MIN_INSNS:
                    unsolved.append((name, rel, sig, body))

    hits = []
    for name, rel, sig, body in unsolved:
        if sig in solved:
            hits.append((len(sig), name, rel, solved[sig]))
    hits.sort(reverse=True)

    print("%d solved signatures, %d unsolved functions >= %d insns"
          % (len(solved), len(unsolved), MIN_INSNS))
    print("%d unsolved functions have a SOLVED function with the identical "
          "opcode sequence\n" % len(hits))
    print("insns  unsolved function              twin (solved)")
    for n, name, rel, twins in hits[:top]:
        tn, tp = twins[0]
        extra = "  (+%d more)" % (len(twins) - 1) if len(twins) > 1 else ""
        print("%5d  %-30s %s%s" % (n, name, tn, extra))
        print("       %-30s %s" % ("in " + rel, tp))


if __name__ == "__main__":
    main()
