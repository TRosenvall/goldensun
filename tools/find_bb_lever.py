#!/usr/bin/env python3
"""find_bb_lever.py -- functions the BASIC-BLOCK LEVER can now reach.

WHAT THE LEVER IS

Assign an argument's constant to a named local in a DIFFERENT BASIC BLOCK from
the call. Crossing a block boundary stops gcc-2.96 keeping the value in a
register, so it rematerialises at the call -- and its rebuild of a
two-instruction constant is the split pair the ROM has, with another argument
scheduled into the gap. See reports/arg-interleave.md and docs/elevation.md.

It retires two shapes that were filed as separate classes:

    arg-interleave      rom  mov r1,#imm / mov r0,#imm / lsl r1,#n
    pool-loads-first    rom  mov r0, r5 / ldr r1,=X / ldr r2,=Y

WHY THIS IS A SEPARATE TOOL

tools/pick_candidates.py REJECTS both shapes -- they were unmatchable when its
filters were written, and each filter was paid for by a wasted round. Those
rejections are now wrong for 417 functions, and right for the ~1,400 others.
The discriminator is mechanical, so it belongs in code rather than in a note
somebody has to remember:

    a basic-block boundary (a `.L` label) must appear BEFORE the first site.

A call does NOT create a boundary. Only a branch does. That is the whole reason
the class survived thirty-six batches: every function it had been attempted on
was straight-line.

REPORTED, NOT FILTERED: how many sites the function has. Every site needs the
lever applied, and each one is a local to declare, so a function with five is
five times the work of one with one -- but it is also the one that shows whether
the lever holds up under repetition.

    python3 tools/find_bb_lever.py                # all, smallest first
    python3 tools/find_bb_lever.py --max-insn 40  # keep it to one screen
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

FUNC = re.compile(r"\.thumb_func_start\s+(\S+)[^\n]*\n(.*?)\.func_end", re.S)
MOVIMM = re.compile(r"^\tmov\t(r\d+), #")
LSL = re.compile(r"^\tlsl\t(r\d+),")
# ANY two-instruction materialisation gets split, not just a shift.
# OvlFunc_943_2008c28 passes -0xa, which gcc builds as `mov r2,#0xa /
# neg r2,r2`, and the ROM splits that pair around the other arguments the
# same way. Missing this made the tool under-report; both forms count.
NEG = re.compile(r"^\tneg\t(r\d+), \1$")
MOVR0 = re.compile(r"^\tmov\tr0,")
POOLARG = re.compile(r"^\tldr\t(r[0-3]), =")
ARGW = re.compile(r"^\t(?:mov|ldr|lsl)\t(r[0-3])\b")
LABEL = re.compile(r"^\.L")


def sites(lines):
    """Indices where either shape occurs, in order."""
    out, pending = [], {}
    for i, l in enumerate(lines):
        if MOVR0.match(l):
            for r in pending:
                pending[r] = i
            continue
        m = MOVIMM.match(l)
        if m:
            pending[m.group(1)] = None
            continue
        m = LSL.match(l) or NEG.match(l)
        if m and pending.get(m.group(1)) is not None:
            out.append(i)
            pending.pop(m.group(1))
            continue
        if m:
            pending.pop(m.group(1), None)
        if l.startswith("\tbl\t"):
            pending.clear()
    # ARGUMENT SETUP IS THE CONTIGUOUS TAIL BEFORE THE CALL, and scanning the
    # whole block instead reports nonsense. The first version of this took every
    # r0-r3 write since the previous `bl`, which caught the VALUE OF A STORE --
    # `mov r3, #0 / strh r3, [r0, #6]` two instructions before an unrelated
    # `ldr r0, =0x915` read as a mov-then-pool argument block, and three of the
    # first four leads it produced were that. Walking back from the `bl` and
    # stopping at the first non-argument instruction is exact for the shape.
    for i, l in enumerate(lines):
        if not l.startswith("\tbl\t"):
            continue
        tail = []
        j = i - 1
        while j >= 0 and ARGW.match(lines[j]):
            tail.append(j)
            j -= 1
        tail.reverse()
        kinds = "".join("P" if POOLARG.match(lines[k]) else "M" for k in tail)
        if "MP" in kinds:
            out.append(tail[0])
    return sorted(set(out))


def parked_names():
    out = set()
    for p in glob.glob(os.path.join(ROOT, "src/non_matching/**/*.c"),
                       recursive=True):
        txt = open(p, errors="replace").read()
        out.update(re.findall(r"\b((?:Ovl)?Func_\w+)\s*\(", txt))
        out.update(re.findall(r"\b((?:Ovl)?Func_\w+)\b", txt.split("*/", 1)[0]))
    return out


def main():
    a = sys.argv[1:]
    lo = int(a[a.index("--min-insn") + 1]) if "--min-insn" in a else 8
    hi = int(a[a.index("--max-insn") + 1]) if "--max-insn" in a else 10 ** 9
    skip = parked_names()
    rows = []
    for p in sorted(glob.glob(os.path.join(ROOT, "asm/**/*.s"), recursive=True)):
        txt = open(p, errors="replace").read()
        if txt.startswith("@ Generated by gcc"):
            continue
        rel = os.path.relpath(p, ROOT)
        nf = txt.count(".thumb_func_start")
        for m in FUNC.finditer(txt):
            if m.group(1) in skip:
                continue
            lines = m.group(2).split("\n")
            n = len([l for l in lines if l.startswith("\t")])
            if not (lo <= n <= hi):
                continue
            s = sites(lines)
            if not s:
                continue
            # THE DISCRIMINATOR. Anything before the first site must include a
            # label, or there is no earlier block to assign the value in.
            if not any(LABEL.match(l) for l in lines[:s[0]]):
                continue
            rows.append((n, len(s), m.group(1), rel, nf))
    rows.sort()
    print(f"{'insn':>4} {'sites':>5} {'fns':>4}  name / file")
    for n, ns, name, rel, nf in rows[:int(a[a.index("--limit") + 1])
                                     if "--limit" in a else 25]:
        print(f"{n:4d} {ns:5d} {nf:4d}  {name}  {rel}")
    print(f"\n{len(rows)} functions the lever reaches, "
          f"{sum(r[1] for r in rows)} sites")
    return 0


if __name__ == "__main__":
    sys.exit(main())
