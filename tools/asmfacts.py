#!/usr/bin/env python3
"""asmfacts.py -- facts about a hand-written .s that decide how to convert it.

WHY THIS IS A MODULE AND NOT A NOTE

`tools/split_s.py` already refuses to convert a single-function .s that also
carries data, and says so in one line. That guard was added in batch 10 after a
whole-file conversion deleted fourteen .incbin tables and broke the link.

In batch 19 the same mistake happened again, from the other direction: a sweep
reported a function as "whole-file", I read that as "no data", generated the .c
and deleted the .s -- without ever invoking split_s.py, so the guard never ran.
Twelve .incbin blobs went with it.

"One function in the file" and "nothing else in the file" are different facts,
and the second is the one that matters. So it lives here, importable, and every
ad-hoc sweep that reports WHOLE should report it by calling carries_data()
rather than by counting functions.

    from asmfacts import carries_data
    tag = "WHOLE+DATA" if carries_data(p) else "WHOLE"

tools/tryc.py cannot cover this: it compiles and does not link, so a stranded
label is invisible to it. The build is the next thing that would notice, which
is several minutes and one bad commit later.
"""
import glob
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def functions(path):
    """Names of the hand-written functions defined in a .s."""
    txt = open(path, errors="replace").read()
    if "Generated by gcc" in txt.split("\n")[0]:
        return []
    return re.findall(r"\.(?:thumb|arm)_func_start(?:_noalign)?\s+(\S+)", txt,
                      re.IGNORECASE)


def carries_data(path):
    """True if the .s holds anything a .c could not take with it.

    Two signals, and either is enough:

      * an .incbin blob -- C cannot express one at all;
      * a label the functions in the file never branch to, which is a data
        label rather than control flow.

    A file that is one function and its own branch targets converts cleanly.
    Anything else strands something at link time.
    """
    txt = open(path, errors="replace").read()
    if "Generated by gcc" in txt.split("\n")[0]:
        return False
    if ".incbin" in txt:
        return True
    defined = set(re.findall(r"^(\.L\w+):", txt, re.M))
    if not defined:
        return False
    # every .L mentioned inside a function body is a branch target
    # NOTE the `[^\n]*` -- a function start may carry a trailing comment
    # (`.thumb_func_start Foo  @ 0x0800ea18`). Requiring a newline straight
    # after the name makes this capture NOTHING, every label then looks
    # unreferenced, and the file is reported as carrying data when it does not.
    # That false positive would block a legitimate whole-file conversion, which
    # is worse than the miss this function exists to prevent.
    bodies = "\n".join(
        m.group(1) for m in
        re.finditer(r"\.thumb_func_start[^\n]*\n(.*?)\.func_end", txt, re.S))
    used = set(re.findall(r"(\.L\w+)", bodies))
    return bool(defined - used)


IDENT = re.compile(r"^(\.L\w+|[A-Za-z_]\w*)$")


def return_targets_are_symbols(rets):
    """True if every `ldr r0, =X` operand is a symbol rather than a number.

    The GetEntrances sweep counts "N compares, N+1 pool loads into r0" and
    treats the loads as table addresses. Several functions satisfy that count
    while loading a NUMBER into r0 -- a flag id passed to __GetFlag, say --
    because the sweep cannot tell a table address from a constant.

    Generated C for those does not compile:

        parse error before `0xf13'

    which is a cheap failure, but it has now cost five generate-and-screen
    cycles across batches 15 and 19. Checking the operand shape before
    generating costs nothing and catches all of them.
    """
    return all(IDENT.match(r) for r in rets)


def deleted_data_sources():
    """.s files deleted in the working tree whose .data or .bss is still wanted.

    THE HOLE orphans() CANNOT SEE. A one-function .s that also carries .incbin
    blobs can be converted whole and the .s deleted, and orphans() will report
    clean -- the .o still has a source, just not one that produces the section
    the linker script asks for. The link then fails with undefined references to
    the data symbols. That happened in batch 43.

    A STATIC CHECK DOES NOT WORK. Twenty linker-script entries in this tree ask
    for `.o(.data)` from objects built from a .c, and all of them are harmless:
    ld contributes nothing and the build is green. A check that fires twenty
    times on a correct tree is worse than no check.

    So this asks a narrower and answerable question instead: which .s files has
    THIS working tree deleted, and does the linker script still want a .data or
    .bss from them? That is exactly the mistake, it has no false positives on a
    clean tree, and it costs one `git status`.
    """
    import subprocess
    r = subprocess.run(["git", "diff", "--name-only", "--diff-filter=D", "HEAD"],
                       capture_output=True, text=True, cwd=ROOT)
    gone = [f for f in r.stdout.split() if f.startswith("asm/") and f.endswith(".s")]
    out = []
    for f in gone:
        o = f[:-2] + ".o"
        for ld in sorted(glob.glob(os.path.join(ROOT, "overlays", "*", "*.ld"))
                         + glob.glob(os.path.join(ROOT, "*.ld"))):
            txt = open(ld, errors="replace").read()
            for sect in ("data", "bss"):
                if re.search(re.escape(o) + r"\(\." + sect + r"\)", txt):
                    out.append((f"{o}(.{sect}) -- .s deleted, section still wanted",
                                os.path.relpath(ld, ROOT)))
    return out


def orphans():
    """Linker-script .o references with neither a .s nor a .c to build them.

    A commit that deletes source can still pass `make -j8 && make compare`:
    make treats an existing .o with no rule as up to date, so the stale object
    from the previous build satisfies the link. `make clean` then removes it
    and the next build dies with "No rule to make target".

    That happened in batch 19 to three overlays at once -- two from splits
    whose generated .c was deleted after it failed to compile, and one from a
    cleanup loop that removed the .s of a function that was never elevated.

    This is the check that answers "is the tree consistent" without a five
    minute rebuild. Run it before committing anything that removes a file.
    """
    out = []
    for ld in sorted(glob.glob(os.path.join(ROOT, "overlays", "*", "*.ld"))
                     + glob.glob(os.path.join(ROOT, "*.ld"))):
        txt = open(ld, errors="replace").read()
        for o in sorted(set(re.findall(r"(asm/[A-Za-z0-9_/]*\.o)", txt))):
            s_path = os.path.join(ROOT, o[:-2] + ".s")
            c_path = os.path.join(ROOT, re.sub(r"^asm/", "src/", o)[:-2] + ".c")
            if not os.path.exists(s_path) and not os.path.exists(c_path):
                out.append((o, os.path.relpath(ld, ROOT)))
                continue
            # AND A .data OR .bss ENTRY NEEDS AN ASSEMBLY SOURCE. A .c produces
            # only .text here, so a script line asking for `X.o(.data)` when the
            # only source is `src/.../X.c` links against nothing.
            #
            # This is the hole batch 43 fell through. A one-function .s that
            # also carried four .incbin blobs was converted whole, the .s
            # deleted, and this check said CLEAN -- because the .o did have a
            # source, just not one that produces the section the script asks
            # for. The link failed with three undefined references.
            #
            # tools/split_s.py refuses that shape and would have said so. It was
            # never run, because the file looked like a one-function file.
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    # --asm-pairs: every elevated .c must have its sibling asm/.s TRACKED.
    #
    # THIS CHECK IS THE OPPOSITE OF WHAT IT FIRST SHIPPED AS, and the reason is
    # worth keeping. Converting a function deletes its hand-written .s, the next
    # build writes a GENERATED .s to the same path, and git reports the file as
    # MODIFIED rather than deleted. That looks exactly like compiler output
    # sneaking into the corpus, so the first version of this check hunted for
    # tracked .s files carrying gcc's "Generated by gcc" banner.
    #
    # It found 2535 of them -- all clean, all arriving with the upstream base
    # commit, and .gitignore covers .o/.d/.elf but deliberately not .s. TRACKING
    # THE GENERATED ASSEMBLY BESIDE THE C IS THE TREE'S CONVENTION, inherited
    # from upstream, and 391 of 391 elevations here follow it.
    #
    # So the failure mode is the reverse: a .c committed WITHOUT its .s. That
    # leaves the pair inconsistent with every other file in the tree and is
    # invisible to the build, which regenerates the .s either way.
    # --unlinked: a src/*.c whose .o NO LINKER SCRIPT REFERENCES.
    #
    # WHY. split_s.py reports "holds only X and no data, convert it directly" for
    # a single-function .s -- meaning the .c replaces THAT file, keeping its
    # name. Writing the .c under the `_b` name a SPLIT would have produced
    # instead leaves the original .s in place, still supplying the function,
    # and the new .o simply unreferenced.
    #
    # Nothing catches that. The build is green, `make compare` passes, and
    # --orphans reports clean, because the stray object is not missing from
    # anything -- it is merely unused. --asm-pairs misses it too while the file
    # is untracked. It happened in batch 59 and was noticed only by reading a
    # directory listing.
    #
    # A GREEN BUILD DOES NOT PROVE A NEW .c IS BEING USED. The linker script
    # reference is what proves it.
    if sys.argv[1] == "--unlinked":
        refs = set()
        for ld in glob.glob(os.path.join(ROOT, "**/*.ld"), recursive=True):
            for m in re.finditer(r"(asm/\S+?\.o)", open(ld, errors="replace").read()):
                refs.add(m.group(1))
        bad = []
        for c in sorted(glob.glob(os.path.join(ROOT, "src/**/*.c"), recursive=True)):
            rel = os.path.relpath(c, ROOT)
            if "non_matching" in rel or rel.startswith("src/lib/"):
                continue
            o = "asm/" + rel[len("src/"):-2] + ".o"
            if o not in refs:
                bad.append(rel)
        for rel in bad:
            print(f"  UNLINKED  {rel}")
        print(f"{len(bad)} source(s) whose .o no linker script references")
        return 1 if bad else 0
    if sys.argv[1] == "--asm-pairs":
        tracked = set(subprocess.run(["git", "ls-files", "asm/"],
                                     capture_output=True, text=True,
                                     cwd=ROOT).stdout.split())
        srcs = subprocess.run(["git", "ls-files", "src/"], capture_output=True,
                              text=True, cwd=ROOT).stdout.split()
        bad = []
        for rel in srcs:
            if not rel.endswith(".c") or "non_matching" in rel:
                continue
            s = "asm/" + rel[len("src/"):-2] + ".s"
            if s not in tracked and os.path.exists(os.path.join(ROOT, s)):
                bad.append(s)
        for s in bad:
            print(f"  UNTRACKED .s for an elevated .c   {s}")
        if bad:
            print(f"\n{len(bad)} .s file(s) need `git add`:")
            print("    git add " + " ".join(bad))
        else:
            print(f"{len(srcs)} sources checked, every elevated .c has a tracked .s")
        return 1 if bad else 0
    if sys.argv[1] == "--orphans":
        bad = orphans() + deleted_data_sources()
        for o, ld in bad:
            print(f"  ORPHAN {o}   ({ld})")
        print(f"{len(bad)} orphaned linker references")
        return 1 if bad else 0
    bad = 0
    for p in sys.argv[1:]:
        rel = os.path.relpath(p, ROOT) if p.startswith("/") else p
        fns = functions(rel)
        data = carries_data(rel)
        if len(fns) == 1 and not data:
            tag = "WHOLE       convert directly"
        elif len(fns) == 1:
            tag = "WHOLE+DATA  needs a hand split -- do NOT delete the .s"
            bad += 1
        else:
            tag = f"{len(fns)} functions  split first"
        print(f"  {tag:48s} {rel}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
